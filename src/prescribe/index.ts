/**
 * Prescribe — AGENTS.md generator (F4 / #16)
 *
 * Transforms supported Findings into one deterministic, reviewable AGENTS.md
 * draft per session. Every rule is derived from the metrics of at least one
 * finding and ends with a `<!-- hindsight: <kind> ×<count> -->` trace comment.
 *
 * This module is pure and browser-safe: it performs no I/O, reads no raw
 * export, and never consults the system clock.
 *
 * Privacy: only non-sensitive, identifier-like metric values are rendered —
 * binary names, tool names, catalogue labels/groups, and counts. Paths,
 * descriptions, `prescription`, evidence and Finding IDs never reach the
 * Markdown. Free-form strings are validated against a strict allowlist and
 * dropped when they do not match.
 *
 * Allowed imports: src/domain/types.ts.
 * Forbidden imports: parser, observe, compare, CLI/UI and Node APIs.
 */

import type { EpochMs, Finding, Prescription } from "../domain/types";
import { prescriptionId } from "./determinism";
export { prescribeOverheadReduction } from "./overhead";
export { prescribeMcpEnablement } from "./mcp";
export { prescribeCustomMode } from "./custom-mode";

type AgentsMdFindingKind =
  | "mcp-candidate"
  | "project-rules-absent"
  | "redundant-read"
  | "retry-after-error"
  | "unused-tool"
  | "human-intervention";

type AgentsMdFinding = Omit<Finding, "kind"> & { kind: AgentsMdFindingKind };

const KIND_ORDER: Readonly<Record<AgentsMdFindingKind, number>> = {
  "mcp-candidate": 0,
  "project-rules-absent": 1,
  "redundant-read": 2,
  "retry-after-error": 3,
  "unused-tool": 4,
  "human-intervention": 5,
};

/** Stable section order in the rendered document. */
const SECTION_HEADINGS = [
  "Environment",
  "Commands",
  "Tool policy",
  "Working agreements",
] as const;
type SectionHeading = (typeof SECTION_HEADINGS)[number];

const DOCUMENT_HEADER =
  "# AGENTS.md\n\n" +
  "<!-- Draft generated by Hindsight from session findings. Each rule ends with a " +
  "hindsight comment naming the finding kind and how many findings support it. " +
  "Review before committing. -->";

/** Identifier-like values only: binaries, tool names, catalogue groups. */
const IDENTIFIER = /^[A-Za-z0-9][A-Za-z0-9._+-]{0,63}$/;
/** Catalogue labels: short human text without markup or path separators. */
const LABEL = /^[A-Za-z0-9][A-Za-z0-9 ._()+-]{0,79}$/;

export interface PrescribeAgentsMdOptions {
  /**
   * Root task IDs (`parentId === null`) of the session. When provided, findings
   * from any other task (subtasks) are ignored so they are not aggregated
   * twice (invariant I-5). Findings do not carry the subtask flag themselves.
   */
  rootTaskIds?: readonly string[];
}

interface Rule {
  text: string;
  kind: AgentsMdFindingKind;
  findingIds: readonly string[];
}

interface Section {
  heading: SectionHeading;
  rules: readonly Rule[];
}

// ---------------------------------------------------------------------------
// Input normalisation
// ---------------------------------------------------------------------------

function isAgentsMdFinding(finding: Finding): finding is AgentsMdFinding {
  return Object.prototype.hasOwnProperty.call(KIND_ORDER, finding.kind);
}

function compareFindings(a: AgentsMdFinding, b: AgentsMdFinding): number {
  return (
    KIND_ORDER[a.kind] - KIND_ORDER[b.kind] ||
    compareStrings(a.sessionId, b.sessionId) ||
    compareStrings(a.taskId, b.taskId) ||
    a.detectedAt - b.detectedAt ||
    compareStrings(a.id, b.id)
  );
}

/** Locale-independent ordering so output is byte-identical everywhere. */
function compareStrings(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function uniqueSupportedFindings(
  findings: readonly Finding[],
  rootTaskIds: ReadonlySet<string> | null
): AgentsMdFinding[] {
  const byId = new Map<string, AgentsMdFinding>();

  for (const finding of findings) {
    if (!isAgentsMdFinding(finding) || byId.has(finding.id)) continue;
    if (rootTaskIds !== null && !rootTaskIds.has(finding.taskId)) continue;
    byId.set(finding.id, finding);
  }

  return [...byId.values()].sort(compareFindings);
}

function groupBySession(
  findings: readonly AgentsMdFinding[]
): Array<readonly AgentsMdFinding[]> {
  const groups = new Map<string, AgentsMdFinding[]>();

  for (const finding of findings) {
    const group = groups.get(finding.sessionId);
    if (group) group.push(finding);
    else groups.set(finding.sessionId, [finding]);
  }

  return [...groups.entries()]
    .sort(([a], [b]) => compareStrings(a, b))
    .map(([, group]) => group);
}

function ofKind(
  findings: readonly AgentsMdFinding[],
  kind: AgentsMdFindingKind
): AgentsMdFinding[] {
  return findings.filter((finding) => finding.kind === kind);
}

function latestDetectedAt(findings: readonly Finding[]): EpochMs {
  let latest = findings[0].detectedAt;
  for (let index = 1; index < findings.length; index++) {
    if (findings[index].detectedAt > latest) latest = findings[index].detectedAt;
  }
  return latest;
}

// ---------------------------------------------------------------------------
// Safe metric readers — anything unexpected degrades to "absent"
// ---------------------------------------------------------------------------

function count(value: unknown): number | null {
  return typeof value === "number" && Number.isInteger(value) && value >= 0
    ? value
    : null;
}

function identifier(value: unknown): string | null {
  return typeof value === "string" && IDENTIFIER.test(value) ? value : null;
}

function label(value: unknown): string | null {
  return typeof value === "string" && LABEL.test(value) ? value : null;
}

function sumCounts(findings: readonly Finding[], read: (f: Finding) => unknown): number | null {
  let total = 0;
  let seen = false;
  for (const finding of findings) {
    const value = count(read(finding));
    if (value === null) continue;
    total += value;
    seen = true;
  }
  return seen ? total : null;
}

function sortedUnique(values: Iterable<string>): string[] {
  return [...new Set(values)].sort(compareStrings);
}

function code(names: readonly string[]): string {
  return names.map((name) => `\`${name}\``).join(", ");
}

function plural(value: number, singular: string, pluralForm = `${singular}s`): string {
  return `${value} ${value === 1 ? singular : pluralForm}`;
}

function ids(findings: readonly Finding[]): string[] {
  return findings.map((finding) => finding.id);
}

// ---------------------------------------------------------------------------
// Section builders — one per target section, each reading only safe metrics
// ---------------------------------------------------------------------------

function environmentSection(findings: readonly AgentsMdFinding[]): Section | null {
  const byServer = new Map<string, AgentsMdFinding[]>();
  for (const finding of ofKind(findings, "mcp-candidate")) {
    const serverLabel = label(finding.metric.serverLabel);
    if (serverLabel === null) continue;
    const group = byServer.get(serverLabel);
    if (group) group.push(finding);
    else byServer.set(serverLabel, [finding]);
  }

  const rules: Rule[] = [];
  for (const serverLabel of sortedUnique(byServer.keys())) {
    const group = byServer.get(serverLabel) ?? [];
    const binaries = sortedUnique(
      group.flatMap((finding) =>
        Array.isArray(finding.metric.binaries)
          ? finding.metric.binaries.flatMap((binary) => identifier(binary) ?? [])
          : []
      )
    );
    const hits = sumCounts(group, (finding) => finding.metric.hitCount);
    const httpHits = sumCounts(group, (finding) => finding.metric.httpHitCount);

    const tools =
      binaries.length > 0
        ? code(binaries)
        : httpHits !== null && httpHits > 0
          ? "HTTP clients"
          : null;
    if (tools === null) continue;

    const observed = hits !== null ? ` (${plural(hits, "shell command")} observed)` : "";
    rules.push({
      kind: "mcp-candidate",
      findingIds: ids(group),
      text:
        `This repo uses ${tools} from the shell${observed}. ` +
        `When the ${serverLabel} is enabled, prefer its tools over raw shell ` +
        `invocations; otherwise group related commands into a single call.`,
    });
  }

  return rules.length > 0 ? { heading: "Environment", rules } : null;
}

function commandsSection(findings: readonly AgentsMdFinding[]): Section | null {
  const absent = ofKind(findings, "project-rules-absent");
  if (absent.length === 0) return null;

  // The export never contains the project's commands, so they are left as
  // explicit placeholders instead of being guessed.
  const findingIds = ids(absent);
  const rule = (text: string): Rule => ({
    kind: "project-rules-absent",
    findingIds,
    text,
  });
  return {
    heading: "Commands",
    rules: [
      rule("Test: <!-- fill in: test command -->"),
      rule("Build: <!-- fill in: build command -->"),
      rule("Lint / typecheck: <!-- fill in: lint command -->"),
      rule(
        "Run the commands above as written; do not explore the repository to rediscover them."
      ),
    ],
  };
}

function redundantReadRule(findings: readonly AgentsMdFinding[]): Rule | null {
  const reads = ofKind(findings, "redundant-read");
  if (reads.length === 0) return null;

  const extraTurns = sumCounts(reads, (finding) => {
    const turns = count(finding.metric.distinctTurns);
    return turns !== null && turns > 0 ? turns - 1 : null;
  });
  const detail =
    extraTurns !== null
      ? `${plural(reads.length, "file")} re-read in ${plural(extraTurns, "extra turn")} without changes`
      : `${plural(reads.length, "file")} re-read without changes`;

  return {
    kind: "redundant-read",
    findingIds: ids(reads),
    text:
      "Re-read a file only after editing it; otherwise reuse what was already read " +
      `and prefer line ranges over full reads (${detail}).`,
  };
}

function retryRules(findings: readonly AgentsMdFinding[]): Rule[] {
  const byTool = new Map<string, AgentsMdFinding[]>();
  for (const finding of ofKind(findings, "retry-after-error")) {
    const toolName = identifier(finding.metric.toolName);
    if (toolName === null) continue;
    const group = byTool.get(toolName);
    if (group) group.push(finding);
    else byTool.set(toolName, [finding]);
  }

  return sortedUnique(byTool.keys()).map((toolName) => {
    const group = byTool.get(toolName) ?? [];
    const attempts = sumCounts(group, (finding) => finding.metric.attemptCount);
    const detail =
      attempts !== null
        ? `${plural(group.length, "retry chain")}, ${plural(attempts, "attempt")}`
        : plural(group.length, "retry chain");
    return {
      kind: "retry-after-error",
      findingIds: ids(group),
      text:
        `When \`${toolName}\` fails, read the error and change the input or approach ` +
        `before calling it again; do not repeat the same call (${detail}).`,
    };
  });
}

interface IdleTool {
  name: string;
  group: string;
}

function idleTools(finding: Finding): IdleTool[] {
  const fromMetric = finding.metric.idleTools;
  if (Array.isArray(fromMetric)) {
    return fromMetric.flatMap((entry): IdleTool[] => {
      if (typeof entry !== "object" || entry === null) return [];
      const record = entry as Record<string, unknown>;
      if (record.essential === true) return [];
      const name = identifier(record.name);
      if (name === null) return [];
      return [{ name, group: identifier(record.group) ?? "other" }];
    });
  }

  const fromEvidence = finding.evidence.unusedTools ?? [];
  return fromEvidence.flatMap((name) => {
    const safe = identifier(name);
    return safe === null ? [] : [{ name: safe, group: "other" }];
  });
}

function unusedToolRules(findings: readonly AgentsMdFinding[]): Rule[] {
  const byGroup = new Map<string, { names: Set<string>; findings: Set<AgentsMdFinding> }>();

  for (const finding of ofKind(findings, "unused-tool")) {
    for (const tool of idleTools(finding)) {
      const entry = byGroup.get(tool.group) ?? { names: new Set(), findings: new Set() };
      entry.names.add(tool.name);
      entry.findings.add(finding);
      byGroup.set(tool.group, entry);
    }
  }

  const groups = sortedUnique(byGroup.keys());
  if (groups.length === 0) return [];

  const allFindings = ofKind(findings, "unused-tool").filter((finding) =>
    groups.some((group) => byGroup.get(group)?.findings.has(finding))
  );
  const toolCount = new Set(groups.flatMap((group) => [...(byGroup.get(group)?.names ?? [])]))
    .size;

  const lead: Rule = {
    kind: "unused-tool",
    findingIds: ids(allFindings),
    text:
      `${plural(toolCount, "loaded tool")} stayed idle (listed below). Use them only when ` +
      "the task calls for them; disable groups that stay idle in a custom mode so their " +
      "definitions leave the context.",
  };

  return [
    lead,
    ...groups.map((group) => {
      const entry = byGroup.get(group) ?? { names: new Set<string>(), findings: new Set() };
      return {
        kind: "unused-tool" as const,
        findingIds: ids([...entry.findings].sort(compareFindings)),
        text: `Idle (${group}): ${code(sortedUnique(entry.names))}.`,
      };
    }),
  ];
}

function toolPolicySection(findings: readonly AgentsMdFinding[]): Section | null {
  const rules: Rule[] = [];
  const redundant = redundantReadRule(findings);
  if (redundant) rules.push(redundant);
  rules.push(...retryRules(findings));
  rules.push(...unusedToolRules(findings));
  return rules.length > 0 ? { heading: "Tool policy", rules } : null;
}

function workingAgreementsSection(findings: readonly AgentsMdFinding[]): Section | null {
  const interventions = ofKind(findings, "human-intervention");
  if (interventions.length === 0) return null;

  const messages = sumCounts(interventions, (finding) => finding.metric.interventionCount);
  const detail =
    messages !== null
      ? `${plural(messages, "mid-task user message")} in ${plural(interventions.length, "separate moment")}`
      : plural(interventions.length, "mid-task intervention");

  return {
    heading: "Working agreements",
    rules: [
      {
        kind: "human-intervention",
        findingIds: ids(interventions),
        text:
          "Before editing, restate the goal and the acceptance criteria; if something is " +
          "ambiguous, ask once, up front, and keep decisions already made for the rest " +
          `of the task (${detail}).`,
      },
    ],
  };
}

function buildSections(findings: readonly AgentsMdFinding[]): Section[] {
  return [
    environmentSection(findings),
    commandsSection(findings),
    toolPolicySection(findings),
    workingAgreementsSection(findings),
  ].filter((section): section is Section => section !== null);
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

function renderRule(rule: Rule): string {
  return `- ${rule.text} <!-- hindsight: ${rule.kind} ×${rule.findingIds.length} -->`;
}

function renderSection(section: Section): string {
  return `## ${section.heading}\n\n${section.rules.map(renderRule).join("\n")}`;
}

function sectionRank(content: string): number {
  const index = SECTION_HEADINGS.findIndex((heading) =>
    content.startsWith(`## ${heading}\n`)
  );
  return index === -1 ? SECTION_HEADINGS.length : index;
}

function renderDocument(sectionContents: readonly string[]): string {
  return [DOCUMENT_HEADER, ...sectionContents].join("\n\n") + "\n";
}

function sectionFindingIds(section: Section): string[] {
  return sortedUnique(section.rules.flatMap((rule) => rule.findingIds));
}

