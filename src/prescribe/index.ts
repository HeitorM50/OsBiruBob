/**
 * Generate the AGENTS.md prescription family from Finding[].
 *
 * Output per session: one `agents-md-section` prescription per rendered
 * section, followed by exactly one `agents-md-file` prescription with the
 * composed draft. Multi-task sessions are aggregated into that single file;
 * pass `rootTaskIds` to exclude subtasks.
 *
 * The session-level prescriptions carry the smallest contributing task ID as
 * `taskId` (the type requires one); `findingIds` lists every contributor.
 */
export function prescribeAgentsMd(
  findings: readonly Finding[],
  options: PrescribeAgentsMdOptions = {}
): Prescription[] {
  const rootTaskIds = options.rootTaskIds ? new Set(options.rootTaskIds) : null;
  const supported = uniqueSupportedFindings(findings, rootTaskIds);
  if (supported.length === 0) return [];

  const result: Prescription[] = [];

  for (const group of groupBySession(supported)) {
    const sections = buildSections(group);
    if (sections.length === 0) continue;

    const sessionId = group[0].sessionId;
    const used = new Set(sections.flatMap(sectionFindingIds));
    const contributors = group.filter((finding) => used.has(finding.id));
    const taskId = sortedUnique(contributors.map((finding) => finding.taskId))[0];
    const findingIds = sortedUnique(used);
    const createdAt = latestDetectedAt(contributors);
    const sectionContents = sections.map(renderSection);

    sections.forEach((section, index) => {
      const sectionIds = sectionFindingIds(section);
      result.push({
        id: prescriptionId("agents-md-section", sessionId, taskId, sectionIds, section.heading),
        sessionId,
        taskId,
        findingIds: sectionIds,
        kind: "agents-md-section",
        status: "pending",
        createdAt: latestDetectedAt(contributors.filter((f) => sectionIds.includes(f.id))),
        content: sectionContents[index],
        rationale: `Rules for "${section.heading}" derived from ${plural(
          sectionIds.length,
          "finding"
        )}; each rule is tagged with its source finding kind.`,
      });
    });

    result.push({
      id: prescriptionId("agents-md-file", sessionId, taskId, findingIds),
      sessionId,
      taskId,
      findingIds,
      kind: "agents-md-file",
      status: "pending",
      createdAt,
      content: renderDocument(sectionContents),
      targetFile: "AGENTS.md",
      rationale:
        `One draft for the session, built from ${plural(findingIds.length, "finding")}. ` +
        "Each rule quotes only counts and tool or binary names from its finding and ends " +
        "with a hindsight comment for traceability; command placeholders must be filled in by hand.",
    });
  }

  return result;
}

/**
 * Render AGENTS.md content from prescriptions produced by prescribeAgentsMd().
 * File prescriptions take precedence because they already contain the composed
 * draft (one per session; several sessions are separated by `---`). With
 * section-only input, a document is composed in the canonical section order.
 */
export function renderAgentsMd(prescriptions: readonly Prescription[]): string {
  const files = prescriptions
    .filter(
      (prescription): prescription is Prescription & { content: string } =>
        prescription.kind === "agents-md-file" && typeof prescription.content === "string"
    )
    .sort(
      (a, b) => compareStrings(a.sessionId, b.sessionId) || compareStrings(a.id, b.id)
    );

  if (files.length > 0) return files.map((file) => file.content).join("\n---\n\n");

  const seen = new Set<string>();
  const sections = prescriptions
    .filter(
      (prescription): prescription is Prescription & { content: string } =>
        prescription.kind === "agents-md-section" && typeof prescription.content === "string"
    )
    .sort(
      (a, b) =>
        sectionRank(a.content) - sectionRank(b.content) ||
        compareStrings(a.sessionId, b.sessionId) ||
        compareStrings(a.id, b.id)
    )
    .map((prescription) => prescription.content)
    .filter((content) => (seen.has(content) ? false : (seen.add(content), true)));

  return sections.length > 0 ? renderDocument(sections) : "";
}
